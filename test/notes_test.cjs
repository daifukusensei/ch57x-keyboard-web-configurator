// Per-key comments: "#@" lines at the top of the file. Import from the user's file, export, round trip, edge cases.
const fs=require('fs'), path=require('path');
const S=path.join(__dirname,'fixtures');
const load=p=>{ const h=fs.readFileSync(p,'utf8'); return new Function(h.match(/<script id="core">([\s\S]*?)<\/script>/)[1]+';return {parseYaml,fromObj,toYaml,normalizeState,blankLayer,validateAction};')(); };
const cur=load(process.argv[2]||require('path').join(__dirname,'../ch57x-keyboard-web-configurator.html'));
const old=load(path.join(S,'before-comments.html'));
const inline=fs.readFileSync(path.join(S,'user.yaml'),'utf8');        // the user's file, same-line comments (no longer read)
// The same file converted to "#@" lines. Git stores it with LF (.gitattributes text=auto), so make it CRLF like the user's files.
const src=fs.readFileSync(path.join(S,'user-notes.yaml'),'utf8').replace(/\r?\n/g,'\r\n');
let fail=0; const eq=(n,a,b)=>{ const x=JSON.stringify(a),y=JSON.stringify(b); if(x!==y){ fail++; console.log('FAIL',n,'\n   got ',x,'\n   want',y); } else console.log('ok  ',n); };
const read=y=>cur.fromObj(cur.parseYaml(y));
const count=s=>s.layers.reduce((n,l)=>n+l.bnotes.flat().filter(Boolean).length+l.knotes.reduce((m,k)=>m+[k.ccw,k.press,k.cw].filter(Boolean).length,0),0);

eq('fixture is CRLF',/\r\n/.test(src),true);
const st=read(src), was=old.fromObj(old.parseYaml(inline));
// 1. nothing about the actions themselves changed
eq('buttons identical to the previous importer',st.layers.map(l=>l.buttons),was.layers.map(l=>l.buttons));
eq('knobs identical to the previous importer',st.layers.map(l=>l.knobs),was.layers.map(l=>l.knobs));
eq('layout',[st.orientation,st.rows,st.columns,st.knobs,st.layers.length],['normal',4,3,4,3]);
// 2. every comment on the right key
const L0=st.layers[0], L1=st.layers[1], L2=st.layers[2];
eq('row 1 has no comments',L0.bnotes[0],['','','']);
eq('row 2 comments are per key',L0.bnotes[1],['IntelliJ split','IntelliJ zen','IntelliJ hide tools']);
eq('row 3 comments',L0.bnotes[2],['vscode side bar toggle','vscode markdown view','vscode markdown view side-by-side']);
eq('row 4 comments',L0.bnotes[3],['vscode split','vscode zen','vscode toggle output']);
eq('knob 1 comments (ccw/press/cw)',L0.knotes[0],{ccw:'decrease zoom (Edge browser & vscode))',press:'default zoom (Edge browser & vscode)',cw:'increase zoom (Edge browser & vscode))'});
eq('knob 2 has none',L0.knotes[1],{ccw:'',press:'',cw:''});
eq('knob 4 comments',L0.knotes[3],{ccw:'volume down',press:'mute',cw:'volume up'});
eq('layer 2 row 4 comments',L1.bnotes[3],['vs 2022 split','vs 2022 full-screen','vs 2022 close output']);
eq('layer 2 rows 2-3 (<000> keys) have none',[L1.bnotes[1],L1.bnotes[2]],[['','',''],['','','']]);
eq('layer 2 knob 1',L1.knotes[0].ccw,'decrease zoom (Edge browser & vscode)');
eq('layer 3 knob 4 press',L2.knotes[3].press,'mute');
eq('total comments found (15 + 9 + 6)',count(st),30);
eq('no unmatched lines',st.unmatchedNotes,0);
// 3. same-line comments are no longer read (support removed on request)
const il=read(inline);
eq('same-line comments are ignored',count(il),0);
eq('…but the mapping still imports unchanged',il.layers.map(l=>[l.buttons,l.knobs]),st.layers.map(l=>[l.buttons,l.knobs]));

// 4. export: "#@" block at the top, key lines untouched
const y1=cur.toYaml(st);
console.log('--- exported (top) ---\n'+y1.split('\n').slice(0,12).join('\n')+'\n---');
const lines=y1.split('\n');
eq('header block comes right after the "Generated by" line',[lines[0].startsWith('# Generated by'),lines[1].startsWith('# Key comments'),lines[3].startsWith('#@ ')],[true,true,true]);
eq('button comment line',y1.includes('\n#@ L1 R2 C1: IntelliJ split\n'),true);
eq('knob comment line',y1.includes('\n#@ L1 K1 ccw: decrease zoom (Edge browser & vscode))\n'),true);
eq('every #@ line comes before "model:"',lines.findIndex(l=>l.startsWith('model:'))>Math.max(...lines.map((l,i)=>l.startsWith('#@')?i:-1)),true);
eq('no comment at the end of any key line',lines.filter(l=>/^\s+-?\s*(\[|ccw:|press:|cw:)/.test(l)&&/#/.test(l.replace(/"[^"]*"/g,''))).length,0);
// 5. round trip is lossless and stable
const st2=read(y1);
eq('round trip keeps buttons',st2.layers.map(l=>l.buttons),st.layers.map(l=>l.buttons));
eq('round trip keeps knobs',st2.layers.map(l=>l.knobs),st.layers.map(l=>l.knobs));
eq('round trip keeps comments',[st2.layers.map(l=>l.bnotes),st2.layers.map(l=>l.knotes)],[st.layers.map(l=>l.bnotes),st.layers.map(l=>l.knotes)]);
eq('second export is identical (stable)',cur.toYaml(st2),y1);
// 6. no comments -> output unchanged from the previous version
const plain=old.fromObj(old.parseYaml(inline));
const noNotes=read(inline);
const body=y=>y.replace(/^# Generated by .*\n/,'');   // the header line changed when the app was renamed
eq('export header names the app',cur.toYaml(noNotes).split('\n')[0],'# Generated by CH57x Keyboard Web Configurator');
eq('without comments the export is byte-identical to the previous version (after the header line)',body(cur.toYaml(noNotes)),body(old.toYaml(plain)));
eq('without comments there is no "#@" block',/#@|# Key comments/.test(cur.toYaml(noNotes)),false);

// 7. edge cases
const base='orientation: normal\nrows: 1\ncolumns: 3\nknobs: 1\nlayers:\n  - buttons:\n      - ["a", "b", "c"]\n    knobs:\n      - ccw: "x"\n        press: "y"\n        cw: "z"\n';
const mk=head=>read(head+'\n'+base);
const odd=['type ; key','C:\\dir\\','x # y; z','\\;','a\\\\b',';;','"quoted" & \'single\'','{a: [1, 2]}','日本語 🎛️','ends with \\'];
odd.forEach(t=>{
  const s4=cur.normalizeState({model:'ch57x-2',orientation:'normal',rows:1,columns:3,knobs:1,layers:[{buttons:[['a','b','c']],knobs:[{ccw:'x',press:'y',cw:'z'}],bnotes:[[t,'',t]],knotes:[{ccw:t,press:'',cw:''}]}]});
  const y=cur.toYaml(s4);
  eq('written as typed: '+t,y.includes('#@ L1 R1 C1: '+t+'\n'),true);
  const b=read(y.replace(/\n/g,'\r\n')).layers[0];
  eq('round trip (CRLF): '+t,[b.bnotes[0],b.knotes[0].ccw],[[t,'',t],t]);
});
eq('a line anywhere in the file counts',read(base+'#@ L1 R1 C2: late\n').layers[0].bnotes[0],['','late','']);
eq('case and spacing are forgiving',mk('#@l1  r1 c3 :  spaced  \n#@ L1 K1 CW: up').layers[0],
  Object.assign(mk('').layers[0],{bnotes:[['','','spaced']],knotes:[{ccw:'',press:'',cw:'up'}]}));
eq('a later line for the same key wins',mk('#@ L1 R1 C1: first\n#@ L1 R1 C1: second').layers[0].bnotes[0],['second','','']);
eq('an empty text clears nothing and adds nothing',count(mk('#@ L1 R1 C1:')),0);
const um=mk('#@ L1 R2 C1: no row 2\n#@ L1 R1 C4: no column 4\n#@ L4 R1 C1: no layer 4\n#@ L1 K2 cw: no knob 2\n#@ L0 R1 C1: layer 0\n#@ nonsense\n#@ L1 R1 C1: ok');
eq('lines naming no key are counted and skipped',[um.unmatchedNotes,count(um),um.layers[0].bnotes[0][0]],[6,1,'ok']);
eq('unmatched count is not saved with the mapping',Object.keys(um).includes('unmatchedNotes'),false);
eq('a same-line comment is not read',count(read(base.replace('["a", "b", "c"]','["a", "b", "c"]  # one; two; three'))),0);
eq('"#" inside quotes is not a comment',read('orientation: normal\nrows: 1\ncolumns: 1\nknobs: 0\nlayers:\n  - buttons:\n      - ["a #b"]  # real\n    knobs: []\n').layers[0].buttons[0][0],'a #b');
eq('"#@" inside a quoted action is an action, not a comment',read('orientation: normal\nrows: 1\ncolumns: 1\nknobs: 0\nlayers:\n  - buttons:\n      - ["#@ L1 R1 C1: x"]\n    knobs: []\n').layers[0].buttons[0][0],'#@ L1 R1 C1: x');
eq('line breaks in a note become spaces',cur.toYaml(cur.normalizeState({model:'m',orientation:'normal',rows:1,columns:1,knobs:0,layers:[{buttons:[['a']],knobs:[],bnotes:[['two\r\nlines\tand tab']],knotes:[]}]})).includes('#@ L1 R1 C1: two lines and tab\n'),true);
// orientation: R/C follow the file's buttons order, also for vertical layouts
const cw=read('#@ L1 R3 C2: bottom right\norientation: clockwise\nrows: 2\ncolumns: 3\nknobs: 0\nlayers:\n  - buttons:\n      - ["a", "b"]\n      - ["c", "d"]\n      - ["e", "f"]\n    knobs: []\n');
eq('vertical layout: R/C index the file\'s buttons rows',[cw.layers[0].buttons[2][1],cw.layers[0].bnotes[2][1]],['f','bottom right']);
// upstream's own example (fixtures/upstream-example.yaml = refs/ch57x-keyboard-tool/example-mapping.yaml, MIT): its plain
// "#" comments must never become key comments or change the mapping, LF or CRLF
const upY=fs.readFileSync(path.join(S,'upstream-example.yaml'),'utf8');
const upStripped=upY.split(/\r?\n/).filter(l=>!/^\s*#/.test(l)).map(l=>l.replace(/\s+#.*$/,'')).join('\n');
[['LF',upY.replace(/\r\n/g,'\n')],['CRLF',upY.replace(/\r?\n/g,'\r\n')]].forEach(([eol,t])=>{
  const u=read(t), plainUp=read(upStripped);
  eq('upstream example ('+eol+'): has "#" comments, none read as key comments',[upY.split('\n').filter(l=>l.includes('#')).length>20,count(u),u.unmatchedNotes],[true,0,0]);
  eq('upstream example ('+eol+'): same mapping as with every comment removed',JSON.stringify([u.orientation,u.rows,u.columns,u.knobs,u.layers.map(l=>[l.buttons,l.knobs])]),JSON.stringify([plainUp.orientation,plainUp.rows,plainUp.columns,plainUp.knobs,plainUp.layers.map(l=>[l.buttons,l.knobs])]));
});
// resizing keeps notes aligned with their keys and pads new cells
const rs=read(y1); rs.rows=5; rs.knobs=5; cur.normalizeState(rs);
eq('grow: existing notes stay, new cells empty',[rs.layers[0].bnotes[1][0],rs.layers[0].bnotes[4],rs.layers[0].knotes[4]],['IntelliJ split',['','',''],{ccw:'',press:'',cw:''}]);
rs.rows=2; rs.knobs=1; cur.normalizeState(rs);
eq('shrink: notes are cut to the new size',[rs.layers[0].bnotes.length,rs.layers[0].knotes.length],[2,1]);
// blank layer / old saved state without notes
const bl=cur.blankLayer({orientation:'normal',rows:2,columns:3,knobs:2});
eq('blankLayer has note arrays',[bl.bnotes.length,bl.bnotes[0].length,bl.knotes.length],[2,3,2]);
const legacy=cur.normalizeState({model:'ch57x-2',orientation:'normal',rows:1,columns:2,knobs:1,layers:[{buttons:[['a','b']],knobs:[{ccw:'',press:'',cw:''}]}]});
eq('state saved by an older version gets empty notes',[legacy.layers[0].bnotes,legacy.layers[0].knotes],[[['','']],[{ccw:'',press:'',cw:''}]]);

fs.writeFileSync(path.join(S,'exported.yaml'),y1);
console.log(fail?fail+' FAILED':'ALL PASSED'); process.exit(fail?1:0);
